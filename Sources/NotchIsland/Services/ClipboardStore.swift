import AppKit
import ApplicationServices

struct ClipItem: Identifiable, Codable, Equatable {
    enum Kind: String, Codable { case text, link, color, file }

    var id = UUID()
    var text: String
    var kind: Kind
    var date = Date()
    var pinned = false
    var sourceApp: String?

    var symbol: String {
        switch kind {
        case .text: return "text.alignleft"
        case .link: return "link"
        case .color: return "paintpalette.fill"
        case .file: return "doc.fill"
        }
    }
}

/// Clipboard history. macOS has no clipboard-change notification, so this checks the pasteboard's
/// change counter (a very cheap call) once a second with generous timer tolerance, and pauses while the screen sleeps.
final class ClipboardStore: ObservableObject {
    @Published private(set) var items: [ClipItem] = []
    @Published private(set) var justCopied: UUID?

    private let prefs: Preferences
    private var timer: Timer?
    private var lastChangeCount = NSPasteboard.general.changeCount
    private static let concealedTypes = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"
    ]

    private var storeURL: URL? {
        FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask).first?
            .appendingPathComponent("NotchIsland", isDirectory: true)
            .appendingPathComponent("clipboard.json")
    }

    init(prefs: Preferences) {
        self.prefs = prefs
        if prefs.clipboardPersist { loadFromDisk() }
    }

    var isRunning: Bool { timer != nil }

    func start() {
        guard timer == nil else { return }
        lastChangeCount = NSPasteboard.general.changeCount
        let t = Timer(timeInterval: 1, repeats: true) { [weak self] _ in self?.check() }
        t.tolerance = 0.5
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    private func check() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount

        let types = pasteboard.types?.map(\.rawValue) ?? []
        if prefs.clipboardIgnoreConcealed && types.contains(where: { Self.concealedTypes.contains($0) }) { return }

        var item: ClipItem?
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], let url = urls.first {
            item = ClipItem(text: url.path, kind: .file)
        } else if let string = pasteboard.string(forType: .string)?.trimmingCharacters(in: .whitespacesAndNewlines), !string.isEmpty {
            item = ClipItem(text: string, kind: Self.kind(of: string))
        }
        guard var newItem = item else { return }
        newItem.sourceApp = NSWorkspace.shared.frontmostApplication?.localizedName
        add(newItem)
    }

    private static func kind(of string: String) -> ClipItem.Kind {
        if string.range(of: #"^#?[0-9A-Fa-f]{6}$"#, options: .regularExpression) != nil { return .color }
        if let url = URL(string: string), let scheme = url.scheme, ["http", "https"].contains(scheme.lowercased()), !string.contains(" ") { return .link }
        return .text
    }

    private func add(_ item: ClipItem) {
        if let index = items.firstIndex(where: { $0.text == item.text }) {
            var existing = items.remove(at: index)
            existing.date = Date()
            items.insert(existing, at: 0)
        } else {
            items.insert(item, at: 0)
        }
        trim()
        save()
    }

    private func trim() {
        let pinned = items.filter(\.pinned)
        let unpinned = items.filter { !$0.pinned }.prefix(max(prefs.clipboardLimit - pinned.count, 0))
        items = pinned + unpinned
    }

    /// Puts the item back on the clipboard and, if enabled and allowed, pastes it into the front app.
    func copy(_ item: ClipItem) {
        copyText(item.text, isFile: item.kind == .file)
        justCopied = item.id
        DispatchQueue.main.asyncAfter(deadline: .now() + 1.2) { [weak self] in
            if self?.justCopied == item.id { self?.justCopied = nil }
        }
    }

    func copyText(_ text: String, isFile: Bool = false) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        if isFile {
            pasteboard.writeObjects([URL(fileURLWithPath: text) as NSURL])
        } else {
            pasteboard.setString(text, forType: .string)
        }
        lastChangeCount = pasteboard.changeCount
        if prefs.clipboardPasteDirectly { pasteIntoFrontApp() }
    }

    func togglePin(_ item: ClipItem) {
        guard let index = items.firstIndex(of: item) else { return }
        items[index].pinned.toggle()
        trim()
        save()
    }

    func remove(_ item: ClipItem) {
        items.removeAll { $0.id == item.id }
        save()
    }

    func clear() {
        items.removeAll { !$0.pinned }
        save()
    }

    // MARK: - Paste (needs Accessibility permission)

    static var canPaste: Bool { AXIsProcessTrusted() }

    static func requestPastePermission() {
        let options = [kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String: true] as CFDictionary
        _ = AXIsProcessTrustedWithOptions(options)
    }

    private func pasteIntoFrontApp() {
        guard Self.canPaste else { return }
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.05) {
            let source = CGEventSource(stateID: .combinedSessionState)
            let down = CGEvent(keyboardEventSource: source, virtualKey: 0x09, keyDown: true)
            let up = CGEvent(keyboardEventSource: source, virtualKey: 0x09, keyDown: false)
            down?.flags = .maskCommand
            up?.flags = .maskCommand
            down?.post(tap: .cghidEventTap)
            up?.post(tap: .cghidEventTap)
        }
    }

    // MARK: - Persistence (opt-in)

    func save() {
        guard prefs.clipboardPersist, let url = storeURL else { return }
        try? FileManager.default.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
        if let data = try? JSONEncoder().encode(items) { try? data.write(to: url, options: .atomic) }
    }

    func deleteSavedHistory() {
        if let url = storeURL { try? FileManager.default.removeItem(at: url) }
    }

    private func loadFromDisk() {
        guard let url = storeURL, let data = try? Data(contentsOf: url),
              let saved = try? JSONDecoder().decode([ClipItem].self, from: data) else { return }
        items = saved
    }
}
